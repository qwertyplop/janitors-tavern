export function t(lang: UILanguage, key: keyof typeof I18N.en, vars?: Params): string {
  const raw = I18N[lang][key] ?? I18N.en[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : raw;
}